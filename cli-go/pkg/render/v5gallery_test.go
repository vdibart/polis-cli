package render

// ⭐ THE THEME GALLERY: the v5 public site drawn in every theme the bundle
// ships, for quick visual checks while a theme is tuned.
//
// It holds no theme of its own. Each theme is read from its one definition
// (themes/<name>/v5.json in the bundle) and drawn by the real v5 shape, over
// the same small site the golden tests render. Tuning a theme means editing
// that definition and generating again:
//
//	make v5-gallery
//
// which runs this test with -v5-gallery=<dir>. Without the flag it does
// nothing. The output is ignored by git and opens from disk with no server:
// <dir>/index.html. The gallery's own chrome (the landing page and the bar on
// every page) is hand-written and kept beside the output, with the v5 design
// files.
//
// ⛔ Nothing private goes into the output: the rendered site only, never its
// .polis directory (the test site's keys live there).

import (
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
	"testing"

	"github.com/vdibart/polis-cli/cli-go/pkg/theme"
)

var v5GalleryDir = flag.String("v5-gallery", "", "write the theme gallery's rendered sites into this directory")

// v5ThemesDir is where the bundle's themes are defined.
const v5ThemesDir = "../bundle/fixtures/pub.polis.core/themes"

// v5ThemeNames are the themes that have a v5 definition, sorted.
func v5ThemeNames(t *testing.T) []string {
	t.Helper()
	entries, err := os.ReadDir(v5ThemesDir)
	if err != nil {
		t.Fatal(err)
	}
	var names []string
	for _, e := range entries {
		if _, err := os.Stat(filepath.Join(v5ThemesDir, e.Name(), theme.V5TokensFile)); e.IsDir() && err == nil {
			names = append(names, e.Name())
		}
	}
	sort.Strings(names)
	return names
}

type galleryTheme struct {
	Name     string            `json:"name"`
	Note     string            `json:"note"`
	Reserved bool              `json:"reserved"`
	Withheld string            `json:"withheld,omitempty"` // why the site draws the polis default instead
	Swatches map[string]string `json:"swatches"`
}

func TestV5Gallery(t *testing.T) {
	out := *v5GalleryDir
	if out == "" {
		t.Skip("generates the theme gallery only with -v5-gallery=<dir> (make v5-gallery)")
	}
	themesOut := filepath.Join(out, "themes")
	// Only the generated part is replaced; the hand-written chrome beside it stays.
	if err := os.RemoveAll(themesOut); err != nil {
		t.Fatal(err)
	}
	var listed []galleryTheme
	for _, name := range v5ThemeNames(t) {
		src, err := os.ReadFile(filepath.Join(v5ThemesDir, name, theme.V5TokensFile))
		if err != nil {
			t.Fatal(err)
		}
		// A definition that fails the contract or the contrast check is withheld
		// and the site draws in the polis default, as a tenant's would; the
		// gallery says why, since tuning is what it is for.
		def, err := theme.ParseV5Theme(src)
		withheld := ""
		if err != nil {
			withheld, def = err.Error(), &theme.V5Theme{Tokens: map[string]string{}}
		} else if problems := theme.CheckV5Contrast(def); len(problems) > 0 {
			why := make([]string, 0, len(problems))
			for _, p := range problems {
				why = append(why, p.String())
			}
			withheld = "fails the contrast check: " + strings.Join(why, "; ")
		}
		sw := map[string]string{}
		for _, k := range []string{"bg", "surface", "site", "text", "accent-2"} {
			sw[k] = def.Get(k)
		}
		if sw["accent-2"] == "site" {
			sw["accent-2"] = sw["site"]
		}
		listed = append(listed, galleryTheme{Name: name, Note: def.Note, Reserved: theme.IsReserved(name), Withheld: withheld, Swatches: sw})

		site := renderV5Site(t, name)
		if err := copyGallerySite(site, filepath.Join(themesOut, name)); err != nil {
			t.Fatalf("%s: %v", name, err)
		}
	}
	b, err := json.MarshalIndent(listed, "", "  ")
	if err != nil {
		t.Fatal(err)
	}
	// A script, not a JSON file: a page opened from disk cannot fetch one.
	js := "// Generated by make v5-gallery from each theme's v5.json. Do not edit.\nwindow.POLIS_GALLERY_THEMES = " + string(b) + ";\n"
	if err := os.WriteFile(filepath.Join(themesOut, "themes.js"), []byte(js), 0o644); err != nil {
		t.Fatal(err)
	}
	t.Logf("theme gallery: %d themes in %s (open %s)", len(listed), themesOut, filepath.Join(out, "index.html"))
}

// copyGallerySite copies a rendered site into the gallery, leaving out what
// is not the public site, and makes every page open from disk with the
// gallery's bar on it.
func copyGallerySite(site, dst string) error {
	return filepath.WalkDir(site, func(p string, d os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		rel, _ := filepath.Rel(site, p)
		if d.IsDir() {
			if rel == ".polis" { // ⛔ the site's keys and private state
				return filepath.SkipDir
			}
			return os.MkdirAll(filepath.Join(dst, rel), 0o755)
		}
		b, err := os.ReadFile(p)
		if err != nil {
			return err
		}
		if strings.HasSuffix(rel, ".html") {
			b = []byte(galleryPage(string(b), filepath.ToSlash(rel), site))
		}
		return os.WriteFile(filepath.Join(dst, rel), b, 0o644)
	})
}

var (
	rootRef      = regexp.MustCompile(`(href|src)="/([^/"][^"]*)?"`)
	widgetScript = regexp.MustCompile(`<script src="https://polis\.pub/widget-[^"]*"[^>]*></script>\n?`)
)

// galleryPage makes a rendered page open from disk: its site-absolute links
// become relative (a page's own address, or the folder's index), polis.pub's
// widget is left out (the gallery's bar stands in for what it draws), and
// the bar is added. The page is otherwise the shape's, byte for byte.
func galleryPage(html, rel, site string) string {
	up := strings.Repeat("../", strings.Count(rel, "/"))
	html = rootRef.ReplaceAllStringFunc(html, func(m string) string {
		sub := rootRef.FindStringSubmatch(m)
		target := sub[2]
		path, rest := target, ""
		if i := strings.IndexAny(target, "?#"); i >= 0 {
			path, rest = target[:i], target[i:]
		}
		switch {
		case path == "":
			path = "index.html"
		case fileExists(filepath.Join(site, path+".html")):
			path += ".html"
		case fileExists(filepath.Join(site, path, "index.html")):
			path = strings.TrimSuffix(path, "/") + "/index.html"
		}
		return fmt.Sprintf(`%s="%s%s%s"`, sub[1], up, path, rest)
	})
	html = widgetScript.ReplaceAllString(html, "")
	bar := fmt.Sprintf(`<link rel="stylesheet" href="%[1]s../../gallery.css">
<script src="%[1]s../themes.js"></script>
<script src="%[1]s../../gallery.js" data-root="%[1]s"></script>
`, up)
	return strings.Replace(html, "</body>", bar+"</body>", 1)
}

func fileExists(p string) bool {
	st, err := os.Stat(p)
	return err == nil && !st.IsDir()
}

// TestV5GalleryPageOpensFromDisk: links become relative, the widget goes,
// the bar comes, and nothing else changes.
func TestV5GalleryPageOpensFromDisk(t *testing.T) {
	site := t.TempDir()
	_ = os.WriteFile(filepath.Join(site, "about.html"), nil, 0o644)
	in := `<a href="/">home</a><a href="/about">about</a><link href="/styles.css?v=1"><a href="https://x.example/">out</a><a href="//cdn.example/a">cdn</a>` +
		`<script src="https://polis.pub/widget-1.js" crossorigin="anonymous" defer></script>` + "\n</body>"
	got := galleryPage(in, "posts/20260315/alpha.html", site)
	for _, want := range []string{`href="../../index.html"`, `href="../../about.html"`, `href="../../styles.css?v=1"`, `href="https://x.example/"`, `href="//cdn.example/a"`, `src="../../../../gallery.js"`} {
		if !strings.Contains(got, want) {
			t.Errorf("lacks %s:\n%s", want, got)
		}
	}
	if strings.Contains(got, "polis.pub/widget") {
		t.Error("polis.pub's widget is still loaded")
	}
}
